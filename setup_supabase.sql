create or replace function private.owns_class(p_class_id uuid)
returns boolean language sql security definer stable set search_path = '' as $$
  select exists(select 1 from public.classrooms c where c.id=p_class_id and c.teacher_id=(select auth.uid()));
$$;
create or replace function private.in_class(p_class_id uuid)
returns boolean language sql security definer stable set search_path = '' as $$
  select exists(select 1 from public.enrollments e where e.class_id=p_class_id and e.student_id=(select auth.uid()));
$$;

