-- 學生只能透過邀請碼申請班級；導師須先核准。
create or replace function public.join_class(p_code text,p_seat_no integer)
returns boolean language plpgsql security definer set search_path='' as $$
declare v_class uuid;
begin
 if auth.uid() is null then raise exception '請先登入'; end if;
 if p_seat_no not between 1 and 60 then raise exception '座號需介於 1 與 60'; end if;
 select id into v_class from public.classrooms where join_code=upper(trim(p_code));
 if v_class is null then raise exception '班級邀請碼不正確'; end if;
 insert into public.enrollments(class_id,student_id,seat_no) values(v_class,auth.uid(),p_seat_no);
 return true;
exception when unique_violation then raise exception '此座號或帳號已送出申請';
end;$$;

-- 由伺服器建立今日配額，當天不得下修，防止臨時改成低標通過。
create or replace function public.begin_day(p_goal integer)
returns integer language plpgsql security definer set search_path='' as $$
declare v_goal integer; v_today date := (now() at time zone 'Asia/Taipei')::date;
begin
 if auth.uid() is null then raise exception '請先登入'; end if;
 if p_goal not in(15,30,50) then raise exception '配額僅限 15、30、50'; end if;
 insert into public.day_plans(user_id,study_date,goal) values(auth.uid(),v_today,p_goal) on conflict do nothing;
 select goal into v_goal from public.day_plans where user_id=auth.uid() and study_date=v_today;
 return v_goal;
end;$$;

-- 每個官方詞目在同一天最多計入一次；不接受任意編造的 word_id。
create or replace function public.submit_pass(p_word_id text)
returns boolean language plpgsql security definer set search_path='' as $$
declare v_today date := (now() at time zone 'Asia/Taipei')::date;
begin
 if auth.uid() is null then raise exception '請先登入'; end if;
 if not exists(select 1 from public.day_plans where user_id=auth.uid() and study_date=v_today) then raise exception '需先開始今日學習'; end if;
 if not exists(select 1 from public.official_words where id=p_word_id) then raise exception '非官方詞目'; end if;
 insert into public.daily_passes(user_id,study_date,word_id) values(auth.uid(),v_today,p_word_id) on conflict do nothing;
 return true;
end;$$;

-- 校驗伺服器詞目數和當天鎖定配額，完成時間用伺服器時鐘。
create or replace function public.finish_day()
returns boolean language plpgsql security definer set search_path='' as $$
declare v_today date := (now() at time zone 'Asia/Taipei')::date;v_goal int;v_passes int;
begin
 if auth.uid() is null then raise exception '請先登入'; end if;
 select goal into v_goal from public.day_plans where user_id=auth.uid() and study_date=v_today;
 if v_goal is null then return false; end if;
 select count(*) into v_passes from public.daily_passes where user_id=auth.uid() and study_date=v_today;
 if v_passes < v_goal then return false; end if;
 insert into public.daily_completions(user_id,study_date,goal,passed_count)
 values(auth.uid(),v_today,v_goal,v_passes) on conflict(user_id,study_date) do nothing;
 return true;
end;$$;

revoke all on function private.owns_class(uuid), private.in_class(uuid) from public, anon;
revoke all on function public.join_class(text,integer),public.begin_day(integer),public.submit_pass(text),public.finish_day() from public, anon;
