create schema if not exists private;
create table if not exists public.teachers (
 user_id uuid primary key references auth.users(id) on delete cascade,
 created_at timestamptz not null default now()
);
create table if not exists public.profiles (
 user_id uuid primary key references auth.users(id) on delete cascade,
 nickname text not null check(char_length(nickname) between 1 and 40),
 created_at timestamptz not null default now()
);
create table if not exists public.student_progress (
 user_id uuid primary key references auth.users(id) on delete cascade,
 payload jsonb not null default '{}'::jsonb,
 updated_at timestamptz not null default now()
);
create table if not exists public.classrooms (
 id uuid primary key default gen_random_uuid(),
 teacher_id uuid not null references auth.users(id) on delete cascade,
 name text not null check(char_length(name) between 2 and 60),
 join_code text not null unique check(join_code ~ '^[A-Z0-9-]{6,25}$'),
 created_at timestamptz not null default now()
);
create table if not exists public.enrollments (
 class_id uuid not null references public.classrooms(id) on delete cascade,
 -- 直接參照 profiles，讓 PostgREST 可由 enrollments 查詢學生顯示名稱。
 student_id uuid not null references public.profiles(user_id) on delete cascade,
 seat_no int not null check(seat_no between 1 and 60),
 approved boolean not null default false,
 requested_at timestamptz not null default now(),
 primary key(class_id,student_id),
 constraint enrollments_one_seat unique(class_id,seat_no)
);
create index if not exists ix_enroll_student on public.enrollments(student_id);
create index if not exists ix_class_teacher on public.classrooms(teacher_id);
create table if not exists public.official_words(id text primary key);
create table if not exists public.day_plans (
 user_id uuid not null references auth.users(id) on delete cascade,
 study_date date not null,
 goal int not null check(goal in(15,30,50)),
 started_at timestamptz not null default now(),
 primary key(user_id,study_date)
);
create table if not exists public.daily_passes (
 user_id uuid not null references auth.users(id) on delete cascade,
 study_date date not null,
 word_id text not null references public.official_words(id),
 passed_at timestamptz not null default now(),
 primary key(user_id,study_date,word_id)
);
create table if not exists public.daily_completions (
 user_id uuid not null references auth.users(id) on delete cascade,
 study_date date not null,
 goal int not null check(goal in(15,30,50)),
 passed_count int not null,
 completed_at timestamptz not null default now(),
 primary key(user_id,study_date)
);
create index if not exists ix_completions_date on public.daily_completions(study_date);

